import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
const base = process.env.CHECK_URL || 'http://127.0.0.1:4331/';
await mkdir('test-results/notes', { recursive: true });
const context = await browser.newContext({ viewport: { width: 390, height: 1000 }, reducedMotion: 'reduce' });
await context.tracing.start({ screenshots: true, snapshots: true });
try {
  const page = await context.newPage();
  const longTag = 'LongTagWithoutSpaces'.repeat(8);
  await page.route('**/notes/**', async route => {
    if (route.request().resourceType() !== 'document') return route.continue();
    const response = await route.fetch();
    const fixture = Array.from({ length: 12 }, (_, i) => `<div data-note data-category="分页测试" data-tags='${JSON.stringify(['共享标签', `标签${i}`, ...(i === 11 ? [longTag] : [])])}'><p>测试笔记 ${i + 1}</p></div>`).join('');
    await route.fulfill({ response, body: (await response.text()).replace('id="note-list">', `id="note-list">${fixture}`) });
  });
  const navigation = page.getByRole('region', { name: '笔记筛选', exact: true });
  const tags = page.getByRole('group', { name: '标签', exact: true });
  const rows = page.locator('[data-note]:visible');
  const open = async query => { await page.goto(new URL('notes/' + query, base).href); await navigation.waitFor(); };
  await open('?category=' + encodeURIComponent('分页测试'));
  assert.equal(await rows.count(), 10);
  await page.getByRole('button', { name: '下一页', exact: true }).click();
  assert.equal(await rows.count(), 2);
  assert.equal(new URL(page.url()).searchParams.get('page'), '2');
  await page.reload(); await navigation.waitFor();
  assert.equal(await rows.count(), 2);
  await tags.getByRole('button', { name: '#共享标签，12 篇笔记', exact: true }).click();
  assert.equal(await rows.count(), 10);
  assert.equal(new URL(page.url()).searchParams.has('page'), false);
  await tags.getByRole('button', { name: '展开全部标签', exact: true }).click();
  await tags.getByRole('button', { name: '#标签9，1 篇笔记', exact: true }).click();
  await tags.getByRole('button', { name: '收起', exact: true }).click();
  assert(await tags.getByRole('button', { name: '#标签9，1 篇笔记', exact: true }).isVisible());
  assert.equal(await rows.count(), 1);
  assert.equal(await page.getByRole('navigation', { name: '笔记分页', exact: true }).count(), 0);
  await page.reload(); await navigation.waitFor();
  assert(await tags.getByRole('button', { name: '#标签9，1 篇笔记', exact: true }).isVisible());
  await tags.getByRole('button', { name: '#标签9，1 篇笔记', exact: true }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => document.activeElement.textContent), '全部');
  assert.equal(await rows.count(), 10);
  await open('?category=' + encodeURIComponent('分页测试') + '&tag=' + encodeURIComponent(longTag));
  assert.equal(await rows.count(), 1);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'test-results/notes/long-tag.png', fullPage: true });
  await open('?category=' + encodeURIComponent('分页测试') + '&page=999');
  assert.equal(await rows.count(), 2);
  assert(await page.getByText('2 / 2', { exact: true }).isVisible());
  await open('?category=' + encodeURIComponent('分页测试') + '&page=-3');
  assert.equal(await rows.count(), 10);
  await tags.getByRole('button', { name: '展开全部标签', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await tags.getByRole('button', { name: '收起', exact: true }).click();
  assert.equal(await tags.getByRole('button').count(), 12);
  await page.setViewportSize({ width: 390, height: 1000 });
  await page.waitForFunction(() => [...document.querySelectorAll('#notes-tags button')].filter(b => !b.hidden).length === 7);
  console.log('Notes pagination passed: 12-note fixture, URL/reload, page reset/clamping, selected overflow tag, keyboard focus, long tag, responsive limits.');
} finally {
  await context.tracing.stop({ path: 'test-results/notes/pagination-trace.zip' });
  await browser.close();
}
